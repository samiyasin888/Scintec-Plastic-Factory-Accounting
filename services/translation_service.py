def create_invoice(invoice_number, customer_name, items, tax_rate):
    conn = get_connection()
    subtotal = sum(item["quantity"] * item["unit_price"] for item in items)
    tax_amount = subtotal * tax_rate
    total = subtotal + tax_amount

    conn.execute(
        "INSERT INTO invoices (invoice_number, invoice_date, customer_name, invoice_type, subtotal, tax_amount, total, notes) VALUES (?, ?, ?, 'sale', ?, ?, ?, 'Generated by Global')",
        (invoice_number, datetime.now().strftime("%Y-%m-%d"), customer_name, subtotal, tax_amount, total),
    )
    invoice_id = conn.execute("SELECT last_insert_rowid()").fetchone()[0]

    for item in items:
        product_name = item["name"]
        quantity = float(item["quantity"])
        unit_price = float(item["unit_price"])
        total_line = quantity * unit_price
        conn.execute(
            "INSERT INTO invoice_items (invoice_id, product_name, quantity, unit_price, total) VALUES (?, ?, ?, ?, ?)",
            (invoice_id, product_name, quantity, unit_price, total_line),
        )

        existing = conn.execute("SELECT id, stock_quantity FROM products WHERE name = ? LIMIT 1", (product_name,)).fetchone()
        if existing:
            new_stock = float(existing["stock_quantity"]) - quantity
            conn.execute("UPDATE products SET stock_quantity = ? WHERE id = ?", (new_stock, existing["id"]))

    conn.commit()
    conn.close()
    return invoice_id


