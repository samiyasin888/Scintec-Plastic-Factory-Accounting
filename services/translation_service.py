def create_payroll(employee_id, period, gross_salary, bonus, deductions):
    net_salary = gross_salary + bonus - deductions
    conn = get_connection()
    conn.execute(
        "INSERT INTO payroll (employee_id, period, gross_salary, bonus, deductions, net_salary) VALUES (?, ?, ?, ?, ?, ?)",
        (employee_id, period, gross_salary, bonus, deductions, net_salary),
    )
    conn.commit()
    conn.close()


def get_payroll():
    conn = get_connection()
    rows = conn.execute(
        "SELECT p.*, e.name AS employee_name FROM payroll p JOIN employees e ON e.id = p.employee_id ORDER BY p.id DESC"
    ).fetchall()
    conn.close()
    return [dict(row) for row in rows]


def get_dashboard_summary():
    conn = get_connection()
    products = conn.execute("SELECT COUNT(*) AS count, COALESCE(SUM(stock_quantity), 0) AS total_stock FROM products").fetchone()
    invoices = conn.execute("SELECT COUNT(*) AS count, COALESCE(SUM(total), 0) AS sales FROM invoices").fetchone()
    employees = conn.execute("SELECT COUNT(*) AS count FROM employees").fetchone()
    conn.close()
    return {
        "products": products["count"],
        "total_stock": products["total_stock"],
        "invoices": invoices["count"],
        "sales": invoices["sales"],
        "employees": employees["count"],
    }
